const { chromium } = require('playwright');
const SP = process.env.SP;
(async () => { const b = await chromium.launch(); const pg = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  const errs = []; pg.on('pageerror', e => errs.push(e.message));
  const closeAll = async () => { while (await pg.$('.sheet [data-a=close]')) await pg.click('.sheet:last-child [data-a=close]'); };
  await pg.goto('http://localhost:8765/');
  await pg.evaluate(async () => { localStorage.clear(); await new Promise(r => { const q = indexedDB.deleteDatabase('satsueicho'); q.onsuccess = q.onerror = q.onblocked = r; }); });
  await pg.reload(); await pg.setInputFiles('#restore', SP + '/work.json'); await pg.click('[data-a=askYes]'); await pg.waitForTimeout(2500); await closeAll();
  await pg.click('[data-a=tab][data-k=shoot]'); await pg.click('[data-a=day] >> nth=0');
  await pg.click('.scard >> nth=0 >> .camd > summary'); await pg.waitForTimeout(300);
  await pg.evaluate(() => document.querySelector('.scard .basis').scrollIntoView({ block: 'center' })); await pg.screenshot({ path: SP + '/b-card.png' });
  console.log('根拠の数（カード）', await pg.locator('.scard .basis button').count());
  await pg.click('.scard .basis button >> nth=0'); await pg.waitForTimeout(200); await pg.screenshot({ path: SP + '/b-prin.png' });
  await pg.click('.sheet:last-child [data-a=openGuide]'); await pg.waitForTimeout(200);
  await pg.fill('#guideq', '望遠'); await pg.waitForTimeout(100);
  console.log('さがす「望遠」で見える原則', await pg.evaluate(() => [...document.querySelectorAll('.sheet:last-child .gitem')].filter(x => !x.hidden).map(x => x.querySelector('summary').textContent)));
  await pg.screenshot({ path: SP + '/b-guide.png' });
  await closeAll();
  await pg.click('.scard >> nth=0 >> [data-a=openRec]'); await pg.waitForTimeout(200);
  console.log('記録の画面の根拠', await pg.evaluate(() => [...document.querySelectorAll('.sheet:last-child .memo .basis button')].map(x => x.textContent).join('、')));
  await closeAll();
  await pg.click('[data-a=tab][data-k=docs]'); await pg.click('#v-docs [data-a=view][data-k=book]'); await pg.waitForTimeout(500);
  console.log('撮影資料の出典ページ', await pg.evaluate(() => { const h = [...document.querySelectorAll('.sheet:last-child .docv h1')].map(x => x.textContent); return h[h.length - 1]; }), await pg.locator('.sheet:last-child .bref').count());
  console.log('errors', errs); await b.close(); })();
